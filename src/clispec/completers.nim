## Completers: the procedures a ``complete = <completer>`` names.
##
## A parameter whose values cannot be listed in the description (paths,
## the names of things that exist only at run time) names a *completer*,
## which the completion engine (``clispec/completion``) calls while the
## user presses Tab. Its type is ``CliCompleter``:
##
## .. code-block:: nim
##   proc (ctx: CliCompletionContext): seq[CliCompletion]
##
## ``ctx.prefix`` is what the user has typed of the value so far; the
## completer returns the values it knows, each with an optional
## description. It may return values that do not start with the prefix: the
## engine keeps only those that do, so a completer can simply list
## everything. A completer may raise a ``CatchableError``; the engine then
## offers nothing for that value rather than failing the completion.
##
## ``complete`` takes any expression of that type: the name of a proc with
## that signature, or a call that returns one (``complete =
## cliCompleteFiles``, ``complete = projectNames(root)``). Anything else is
## a compile error naming the parameter, generated by
## ``cliModelTypeChecks`` through ``cliCompleterFits``.
##
## This module has no dependency on the rest of the library beyond the
## standard library, so the description language can check completers
## without importing the engine.

import std/[os, strutils]

type
  CliCompletion* = object
    ## One candidate the completion engine offers.
    value*: string
      ## The word (or the end of the word) the shell inserts.
    description*: string
      ## Shown beside the value by the shells that show descriptions
      ## (Zsh, Fish, PowerShell); may be empty.

  CliCompletionContext* = object
    ## What a completer is told about the value being completed.
    program*: string
      ## The program's name.
    commandPath*: seq[string]
      ## The canonical words of the command the value belongs to (empty
      ## for the root).
    param*: string
      ## The parameter's name, as declared.
    words*: seq[string]
      ## The words before the one being completed, without the program name.
    prefix*: string
      ## What has been typed of the value so far (for a list with a
      ## ``separator``, of the current element only).

  CliCompleter* = proc (ctx: CliCompletionContext): seq[CliCompletion] {.
    closure, raises: [CatchableError].}
    ## The type a ``complete = <completer>`` expression must have. A plain
    ## (``nimcall``) proc of this signature converts to it.

template cliCompleterFits*(completer: untyped): bool =
  ## Whether ``completer`` is a value of ``CliCompleter``. Used by the checks
  ## ``cliModelTypeChecks`` generates.
  compiles((block:
    let clispecProbe {.used.}: CliCompleter = completer
    clispecProbe))

func cliCompletions*(values: openArray[string]): seq[CliCompletion] =
  ## Candidates without descriptions, one per value.
  for v in values:
    result.add(CliCompletion(value: v))

proc listPaths(prefix: string; directoriesOnly: bool): seq[CliCompletion] {.
    raises: [CatchableError].} =
  ## The entries of the directory ``prefix`` names (the part up to its last
  ## path separator, or the current directory) whose names start with the
  ## rest of ``prefix``. Directories end with ``/``, so the user can keep
  ## typing into them. Names starting with ``.`` are listed only when the
  ## typed part starts with ``.``.
  var cut = -1
  for i in countdown(prefix.high, 0):
    if prefix[i] == '/' or (DirSep != '/' and prefix[i] == DirSep):
      cut = i
      break
  let dirPart = if cut >= 0: prefix[0 .. cut] else: ""
  let namePart = if cut >= 0: prefix[cut + 1 .. ^1] else: prefix
  let dir = if dirPart.len == 0: "." else: expandTilde(dirPart)
  if not dirExists(dir):
    return
  for kind, path in walkDir(dir, relative = true):
    if not path.startsWith(namePart):
      continue
    if path.startsWith(".") and not namePart.startsWith("."):
      continue
    let isDir = kind in {pcDir, pcLinkToDir}
    if directoriesOnly and not isDir:
      continue
    result.add(CliCompletion(value: dirPart & path & (if isDir: "/" else: "")))

proc cliCompleteFiles*(ctx: CliCompletionContext): seq[CliCompletion] {.
    raises: [CatchableError].} =
  ## A completer for paths: the files and directories under the directory
  ## the prefix names.
  listPaths(ctx.prefix, directoriesOnly = false)

proc cliCompleteDirectories*(ctx: CliCompletionContext): seq[CliCompletion] {.
    raises: [CatchableError].} =
  ## A completer for directory paths.
  listPaths(ctx.prefix, directoriesOnly = true)
