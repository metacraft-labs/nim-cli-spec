## The completion scripts: one small script per shell that registers
## completion for a program and asks the program itself for the candidates
## (the protocol of ``clispec/completion``).
##
## The scripts hold no knowledge of the command line: they pass the words
## being completed to ``<program> __complete <shell> ...`` and hand what it
## prints to the shell. So completion always matches the installed program,
## its dynamic values included, and a script never needs regenerating when
## the command line changes.
##
## Each script is safe with any word the user types: words reach the program
## as separate arguments (PowerShell's encoded, see ``clispec/completion``),
## and the program's answer is read line by line as data; nothing it prints
## is evaluated.
##
## How each script is installed:
##
## * **Bash**: ``source <(tool completion bash)`` in ``~/.bashrc``, or the
##   script saved as ``~/.local/share/bash-completion/completions/tool``.
## * **Zsh**: the script saved as ``_tool`` in a directory of ``$fpath``
##   before ``compinit`` runs; or ``source <(tool completion zsh)`` after
##   ``compinit`` in ``~/.zshrc``.
## * **Fish**: the script saved as ``~/.config/fish/completions/tool.fish``.
## * **PowerShell**: ``tool completion powershell | Out-String |
##   Invoke-Expression`` in ``$PROFILE``.

import std/strutils

import ./[parser, completion]

func functionName(program: string): string =
  ## A shell function name derived from the program name.
  result = "_clispec_complete_"
  for ch in program:
    result.add(if ch in {'a'..'z', 'A'..'Z', '0'..'9', '_'}: ch else: '_')

func posixQuote(s: string): string =
  ## ``s`` as one word for bash, zsh and fish: as is when it holds only
  ## safe characters, else single-quoted (bash and zsh close the quote around
  ## an embedded ``'``; fish escapes it inside the quotes).
  var plain = s.len > 0
  for ch in s:
    if ch notin {'a'..'z', 'A'..'Z', '0'..'9', '_', '-', '.', '/', '+', ':',
        '@', ',', '%'}:
      plain = false
  if plain: s else: "'" & s.replace("'", "'\\''") & "'"

func fishQuote(s: string): string =
  var plain = s.len > 0
  for ch in s:
    if ch notin {'a'..'z', 'A'..'Z', '0'..'9', '_', '-', '.', '/', '+', ':',
        '@', ',', '%'}:
      plain = false
  if plain: s
  else: "'" & s.replace("\\", "\\\\").replace("'", "\\'") & "'"

func powerShellLiteral(s: string): string =
  ## ``s`` as a PowerShell single-quoted string. PowerShell also reads the
  ## typographic single quotes (U+2018 to U+201B) as quote characters, so
  ## each of those is doubled too
  ## (https://learn.microsoft.com/powershell/module/microsoft.powershell.core/about/about_quoting_rules).
  cliPowerShellSingleQuote(s)

func commentSafe(s: string): string =
  ## ``s`` for a comment line of a script: control characters (a line
  ## break would end the comment) become spaces.
  result = s
  for ch in result.mitems:
    if ch < ' ' or ch == '\x7f':
      ch = ' '

const
  bashTemplate = """
# bash completion for $PROGRAM, generated by clispec.
# Install: source <($PROGRAM completion bash) in ~/.bashrc, or save this as
# ~/.local/share/bash-completion/completions/$PROGRAM.
$FUNCTION() {
    local reply candidate
    # The program reads the command line up to the cursor itself, with
    # bash's quoting, and answers with what replaces the word being
    # completed, already quoted for bash: one candidate per line.
    reply=$(command $COMMAND $ENTRY bash "$COMP_WORDBREAKS" "${COMP_LINE:0:COMP_POINT}" 2>/dev/null) || return 0
    COMPREPLY=()
    while IFS= read -r candidate; do
        [[ -n $candidate ]] && COMPREPLY+=("$candidate")
    done <<< "$reply"
    # A lone `--flag=` or directory is completed further, not ended.
    if (( ${#COMPREPLY[@]} == 1 )) && [[ ${COMPREPLY[0]} == *[=/] ]]; then
        compopt -o nospace 2>/dev/null
    fi
    return 0
}
complete -F $FUNCTION $NAME
"""

  zshTemplate = """
#compdef $NAME
# zsh completion for $PROGRAM, generated by clispec.
# Install: save this as _$PROGRAM in a directory of $fpath (before compinit
# runs), or source <($PROGRAM completion zsh) after compinit in ~/.zshrc.
$FUNCTION() {
    local reply line value described=0
    local -a lines plain plainShown open openShown
    # The words after the program name, up to and including the one being
    # completed, unquoted; the answer is one `value<TAB>description` per line.
    reply="$(command $COMMAND $ENTRY zsh "${(@Q)words[2,CURRENT]}" 2>/dev/null)" || return 1
    lines=("${(@f)reply}")
    for line in "${lines[@]}"; do
        [[ -z $line ]] && continue
        value="${line%%$'\t'*}"
        if [[ $line == *$'\t'* ]]; then
            described=1
            line="$value  -- ${line#*$'\t'}"
        fi
        # A `--flag=` or a directory is completed further, not ended.
        if [[ $value == *[=/] ]]; then
            open+=("$value"); openShown+=("$line")
        else
            plain+=("$value"); plainShown+=("$line")
        fi
    done
    local -a layout
    (( described )) && layout=(-l)
    (( ${#plain} )) && compadd "${layout[@]}" -d plainShown -a plain
    (( ${#open} )) && compadd "${layout[@]}" -S '' -d openShown -a open
    return 0
}
if [[ "${zsh_eval_context[-1]}" == loadautofunc ]]; then
    $FUNCTION "$@"
else
    compdef $FUNCTION $NAME
fi
"""

  fishTemplate = """
# fish completion for $PROGRAM, generated by clispec.
# Install: save this as ~/.config/fish/completions/$PROGRAM.fish.
function $FUNCTION
    # The words after the program name, unescaped, then the word being
    # completed; the answer is one `value<TAB>description` per line, which
    # is fish's own format.
    # (`-x` needs fish 3.8 or later; `-o` is its older spelling.)
    set -l words (commandline -xpc 2>/dev/null)
    or set words (commandline -opc)
    set -e words[1]
    set -l current (commandline -ct | string unescape --style=script)
    command $COMMAND $ENTRY fish $words "$current" 2>/dev/null
end
complete -c $NAME -e
complete -c $NAME -f -a '($FUNCTION)'
"""

  powerShellTemplate = """
# PowerShell completion for $PROGRAM, generated by clispec.
# Install: $PROGRAM completion powershell | Out-String | Invoke-Expression
# in $PROFILE.
Register-ArgumentCompleter -Native -CommandName $NAME -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    # The words after the program name up to the cursor, then the word being
    # completed. Each is passed as ':' and the base64 of its UTF-8 bytes,
    # because some PowerShell versions drop empty arguments and mangle quotes
    # when they call a native program.
    $words = [System.Collections.Generic.List[string]]::new()
    $current = ''
    $elements = $commandAst.CommandElements
    for ($i = 1; $i -lt $elements.Count; $i++) {
        $element = $elements[$i]
        if ($element.Extent.StartOffset -ge $cursorPosition) { break }
        if ($element.Extent.EndOffset -ge $cursorPosition) {
            $current = $wordToComplete
            if ($current.Length -ge 1 -and $current[0] -eq "'") {
                # Inside single quotes `''` is one quote; a lone `'` at the
                # end closes the string.
                $m = [regex]::Match($current.Substring(1), "^((?:[^']|'')*)'?$")
                if ($m.Success) { $current = $m.Groups[1].Value.Replace("''", "'") }
            } elseif ($current.Length -ge 1 -and $current[0] -eq '"') {
                $current = $current.Substring(1).TrimEnd('"')
            }
            break
        }
        if ($element -is [System.Management.Automation.Language.StringConstantExpressionAst]) {
            $words.Add($element.Value)
        } else {
            $words.Add($element.Extent.Text)
        }
    }
    $words.Add($current)
    $encoded = @($words | ForEach-Object {
        ':' + [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($_))
    })
    $previousEncoding = [Console]::OutputEncoding
    try { [Console]::OutputEncoding = [Text.Encoding]::UTF8 } catch { }
    try {
        $reply = @(& $COMMAND $ENTRY powershell @encoded 2>$null)
    } finally {
        try { [Console]::OutputEncoding = $previousEncoding } catch { }
    }
    # One `completion text<TAB>list text<TAB>tooltip` per line; the
    # completion text is already quoted for PowerShell.
    foreach ($line in $reply) {
        if (-not $line) { continue }
        $fields = $line -split "`t", 3
        if ($fields.Count -lt 3) { continue }
        [System.Management.Automation.CompletionResult]::new(
            $fields[0], $fields[1], 'ParameterValue', $fields[2])
    }
}
"""

func fill(tmpl: string; pairs: openArray[(string, string)]): string =
  ## ``tmpl`` with each ``$KEY`` placeholder replaced, in one pass over the
  ## template, so a value that happens to contain ``$KEY`` text is never
  ## substituted again. Placeholders are upper-case, so the shells' own
  ## ``$name`` variables are left alone.
  var i = if tmpl.startsWith("\n"): 1 else: 0
  while i < tmpl.len:
    var matched = false
    if tmpl[i] == '$':
      for (key, value) in pairs:
        if tmpl.continuesWith(key, i + 1):
          result.add(value)
          i += key.len + 1
          matched = true
          break
    if not matched:
      result.add(tmpl[i])
      inc i

func cliCompletionScript*(shell: CliShell; program: string;
                          command = ""; options = CliOptions()): string =
  ## The completion script of ``shell`` for the program named ``program``
  ## (the command name completion is registered for). ``command`` is what
  ## the script runs to ask for candidates, ``program`` when empty; the
  ## script passes it the completion entry word of ``options``
  ## (``__complete`` by default).
  let cmd = if command.len > 0: command else: program
  let entry = cliCompletionEntry(options)
  case shell
  of cshBash:
    fill(bashTemplate, [("FUNCTION", functionName(program)),
      ("COMMAND", posixQuote(cmd)), ("ENTRY", posixQuote(entry)),
      ("NAME", posixQuote(program)), ("PROGRAM", commentSafe(program))])
  of cshZsh:
    fill(zshTemplate, [("FUNCTION", functionName(program)),
      ("COMMAND", posixQuote(cmd)), ("ENTRY", posixQuote(entry)),
      ("NAME", posixQuote(program)), ("PROGRAM", commentSafe(program))])
  of cshFish:
    fill(fishTemplate, [("FUNCTION", functionName(program)),
      ("COMMAND", fishQuote(cmd)), ("ENTRY", fishQuote(entry)),
      ("NAME", fishQuote(program)), ("PROGRAM", commentSafe(program))])
  of cshPowerShell:
    fill(powerShellTemplate, [("COMMAND", powerShellLiteral(cmd)),
      ("ENTRY", powerShellLiteral(entry)),
      ("NAME", powerShellLiteral(program)),
      ("PROGRAM", commentSafe(program))])
